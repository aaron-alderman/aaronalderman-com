import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { sources, scenes } from './dist/world.js';
import { coverage } from './dist/expansion.js';
const root=path.dirname(fileURLToPath(import.meta.url)),corpusRoot=path.resolve(root,'../..');
const output=path.join(root,'dist/library');fs.mkdirSync(output,{recursive:true});
const receipts={};
for(const [key,source] of Object.entries(sources)){
 if(!source.path)continue;
 const original=path.resolve(corpusRoot,source.path);
 if(!original.startsWith(corpusRoot+path.sep))throw Error('Source escaped corpus root');
 const bytes=fs.readFileSync(original),sha256=crypto.createHash('sha256').update(bytes).digest('hex');
 const href=`library/${key}.txt`;fs.writeFileSync(path.join(root,'dist',href),bytes);
 receipts[key]={path:source.path,href,sha256,bytes:bytes.length,kind:source.kind};
}
fs.writeFileSync(path.join(root,'dist/source-receipts.js'),`// Exact bundled source bytes. Generated by build-source-library.mjs.\nexport const sourceReceipts = ${JSON.stringify(receipts,null,2)};\n`);
const audit={scope:'Curated reader coverage of the ten gaps identified in the chat; not exhaustive exposition of every corpus claim and not scientific closure.',sceneCount:Object.keys(scenes).length,areas:coverage.map(area=>({...area,sources:area.sourceKeys.map(key=>({key,...receipts[key]}))})),bundledSourceCount:Object.keys(receipts).length,retention:'Visited scene IDs and a motion preference only. Exercise answers and psychological profiles are not retained.',publication:'Existing owner-private Worldwright Site; access must be checked before deployment.'};
fs.writeFileSync(path.join(root,'dist/coverage.json'),JSON.stringify(audit,null,2)+'\n');
console.log(`Bound ${Object.keys(receipts).length} source texts to ${audit.sceneCount} scenes and ${audit.areas.length} wider-world regions.`);
